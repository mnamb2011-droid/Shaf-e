def build_fts5_index(cur: sqlite3.Cursor) -> None:
    """Populate the FTS5 virtual table with normalized Arabic tokens across issues, opinions, scholars, references, and terminology synonyms."""
    cur.execute("DELETE FROM search_index")
    issues = cur.execute("SELECT id, title, fiqh_classification, issue_framing, short_ruling, mutamad_summary, qadim_summary, jadid_summary, historical_evolution, reason_for_disagreement, keywords_normalized FROM issues").fetchall()

    for row in issues:
        issue_id = row[0]
        title_norm = normalize_arabic(row[1])

        # Gather opinions text
        op_rows = cur.execute(
            """SELECT o.opinion_text, o.reasoning_summary, s.full_name, s.common_name
               FROM opinions o JOIN scholars s ON o.scholar_id = s.id
               WHERE o.issue_id = ?""",
            (issue_id,),
        ).fetchall()
        opinions_text = " ".join(f"{r[0]} {r[1]}" for r in op_rows)
        scholars_text = " ".join(f"{r[2]} {r[3]}" for r in op_rows)

        # Gather reference titles
        ref_rows = cur.execute(
            """SELECT DISTINCT rw.title
               FROM opinion_sources os
               JOIN opinions o ON os.opinion_id = o.id
               JOIN reference_works rw ON os.reference_id = rw.id
               WHERE o.issue_id = ?""",
            (issue_id,),
        ).fetchall()
        refs_text = " ".join(r[0] for r in ref_rows)

        # Gather chapter & book title
        ctx_row = cur.execute(
            """SELECT b.title, c.title
               FROM issues i
               JOIN chapters c ON i.chapter_id = c.id
               JOIN books b ON c.book_id = b.id
               WHERE i.id = ?""",
            (issue_id,),
        ).fetchone()
        ctx_text = f"{ctx_row[0]} {ctx_row[1]}" if ctx_row else ""

        body_norm = normalize_arabic(
            " ".join([row[2], row[3], row[4], row[5], row[6], row[7], row[8], row[9], opinions_text, ctx_text])
        )
        scholars_norm = normalize_arabic(scholars_text)
        refs_norm = normalize_arabic(refs_text)
        keywords_norm = normalize_arabic(f"{row[10]} {ctx_text}")

        cur.execute(
            """INSERT INTO search_index(issue_id, title_norm, body_norm, scholars_norm, references_norm, keywords_norm)
               VALUES (?, ?, ?, ?, ?, ?)""",
            (issue_id, title_norm, body_norm, scholars_norm, refs_norm, keywords_norm),
        )


def main() -> None:
    if OUT_DB.exists():
        OUT_DB.unlink()

    conn = sqlite3.connect(OUT_DB)
    conn.execute("PRAGMA foreign_keys = ON;")
    schema_sql = SCHEMA_PATH.read_text(encoding="utf-8")
    conn.executescript(schema_sql)

    cur = conn.cursor()
    populate_metadata(cur)
    populate_verification_statuses(cur)
    populate_books_and_chapters(cur)
    populate_periods_and_scholars(cur)
    populate_references_editions_manuscripts(cur)
    populate_terminology(cur)
    populate_issues_and_opinions(cur)
    build_fts5_index(cur)

    conn.commit()
    conn.execute("ANALYZE;")
    conn.execute("VACUUM;")
    conn.close()

    # Compress to .db.gz for minimal APK asset footprint & pack distribution
    with open(OUT_DB, "rb") as f_in, gzip.open(OUT_GZ, "wb", compresslevel=9) as f_out:
        shutil.copyfileobj(f_in, f_out)

    ASSET_GZ.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(OUT_GZ, ASSET_GZ)

    db_size = OUT_DB.stat().st_size
    gz_size = OUT_GZ.stat().st_size
    print(f"Built database successfully: {OUT_DB} ({db_size:,} bytes / {db_size/1024:.1f} KB)")
    print(f"Compressed asset pack:       {OUT_GZ} ({gz_size:,} bytes / {gz_size/1024:.1f} KB)")
    print(f"Copied into Android assets:  {ASSET_GZ}")


if __name__ == "__main__":
    main()
