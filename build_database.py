# Arabic diacritics (Tashkeel) and Tatweel regex
ARABIC_DIACRITICS_RE = re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")


def normalize_arabic(text: str) -> str:
    """Mirror of ArabicNormalizer.kt for consistent FTS5 indexing & querying."""
    if not text:
        return ""
    s = ARABIC_DIACRITICS_RE.sub("", text)
    s = s.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").replace("ٱ", "ا")
    s = s.replace("ى", "ي").replace("ئ", "ي").replace("ؤ", "و")
    s = s.replace("ة", "ه")
    s = re.sub(r"[^\w\s\u0600-\u06FF]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


